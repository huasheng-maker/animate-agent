// Run: playwright-cli -s=lidar run-code --filename=scripts/verify-lidar-browser.cjs
async (page) => {
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  await page.goto('http://localhost:3000/demos/lidar');
  await page.setViewportSize({ width: 1440, height: 1200 });
  await page.getByRole('button', { name: '02 给车身留空间' }).click();
  await page.screenshot({ path: 'output/playwright/lidar-inflation.png', fullPage: true });
  await page.getByRole('button', { name: '03 寻找一条可行路' }).click();
  await page.getByRole('button', { name: 'Play video', exact: true }).click();
  await page.getByText('0:10 / 0:24', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Pause video', exact: true }).click();
  await page.screenshot({ path: 'output/playwright/lidar-search.png', fullPage: true });
  await page.getByRole('button', { name: '04 用运动检验答案' }).click();
  const before = await page.locator('canvas').evaluate((c) => c.toDataURL());
  await page.getByRole('button', { name: 'Play video', exact: true }).click();
  await page.getByText('0:17 / 0:24', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Pause video', exact: true }).click();
  const after = await page.locator('canvas').evaluate((c) => c.toDataURL());
  assert(before !== after, 'Playback must change the rendered frame');
  await page.screenshot({ path: 'output/playwright/lidar-route.png', fullPage: true });
  await page.getByRole('button', { name: 'Play video', exact: true }).click();
  await page.getByText('0:23 / 0:24', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Pause video', exact: true }).click();
  await page.screenshot({ path: 'output/playwright/lidar-arrived.png', fullPage: true });
  const status = page.getByTestId('plan-result');
  assert((await status.innerText()).includes('14.8 m'), 'Default path length');
  await page.getByRole('slider', { name: '货架纵向位置', exact: true }).focus();
  await page.getByRole('slider', { name: '货架纵向位置', exact: true }).press('Home');
  assert(!(await status.innerText()).includes('14.8 m'), 'Moving a shelf must recompute the path');
  await page.getByRole('button', { name: 'Play video', exact: true }).waitFor();
  await page.getByRole('button', { name: '重置', exact: true }).click();
  await page.getByRole('slider', { name: '雷达量程', exact: true }).focus();
  await page.getByRole('slider', { name: '雷达量程', exact: true }).press('Home');
  assert((await status.innerText()).includes('14.8 m'), 'Known-map route must not depend on scan range');
  await page.getByRole('combobox', { name: '规划依据', exact: true }).selectOption('sensor');
  assert((await status.innerText()).includes('保持停止'), 'Unknown space must not be traversed');
  await page.getByRole('button', { name: '02 给车身留空间' }).click();
  await page.screenshot({ path: 'output/playwright/lidar-unknown.png', fullPage: true });
  await page.getByRole('button', { name: '重置', exact: true }).click();
  await page.getByRole('combobox', { name: '实验环境', exact: true }).selectOption('gap');
  await page.getByRole('slider', { name: '机器人半径', exact: true }).focus();
  await page.getByRole('slider', { name: '机器人半径', exact: true }).press('Home');
  assert((await status.innerText()).includes('找到可行路径'), 'Small robot fits gap');
  await page.getByRole('slider', { name: '机器人半径', exact: true }).press('End');
  assert((await status.innerText()).includes('没有可行路径'), 'Large robot does not fit gap');
  await page.screenshot({ path: 'output/playwright/lidar-narrow-door.png', fullPage: true });
  await page.getByRole('combobox', { name: '实验环境', exact: true }).selectOption('wall');
  assert((await status.innerText()).includes('没有可行路径'), 'Full wall must block the goal');
  await page.getByRole('button', { name: '04 用运动检验答案' }).click();
  await page.screenshot({ path: 'output/playwright/lidar-no-route.png', fullPage: true });
  await page.getByRole('button', { name: /没有找到路径，是算法坏了吗/ }).click();
  assert(await page.getByText(/停止比虚构一条穿墙路线正确/).isVisible(), 'Learning check reveals explanation');
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'No mobile horizontal overflow');
  await page.screenshot({ path: 'output/playwright/lidar-mobile.png', fullPage: true });
  assert(errors.length === 0, errors.join('\n'));
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.getByRole('button', { name: '重置', exact: true }).click();
  await page.getByRole('button', { name: '04 用运动检验答案' }).click();
  return { status: 'passed', browserErrors: errors, checks: ['play/pause', 'chapter seek', 'canvas motion and arrival', 'shelf edit', 'range vs prior map', 'unknown blocks', 'narrow door', 'no route', 'reset', 'knowledge check', 'mobile overflow'] };
}
